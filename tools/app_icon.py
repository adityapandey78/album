"""Builds Album's launcher icons from one drawing: the Prints mark (a fanned stack of prints, the top one a photo with a sun).

Writes, under app/src/main/res:
- drawable/ic_launcher_foreground_<accent>.xml: the mark in colour, the sun in that accent (Mono's sun is cut out, since
  its accent is the paper itself; Wallpaper's follows the phone's palette)
- mipmap-anydpi/ic_launcher_<accent>.xml: the adaptive icons, one per launcher entry (activity-alias) in the manifest
- drawable/ic_launcher_monochrome.xml: the one-colour layer Android tints for themed icons
- drawable/ic_notification.xml: the same one-colour prints, cropped to fill the status bar's 24dp
- the disguises (Disguise.kt): for each, mipmap-anydpi/ic_disguise_<name>.xml and its drawable/ic_disguise_<name>_background,
  _foreground and _monochrome layers. Plain everyday shapes of Album's own, so a disguise looks like a generic app of its
  kind and never like any real brand's icon

Stdlib only:  python3 -I tools/app_icon.py
The in-app logo (LogoMark in Components.kt) draws the same shapes; change both together.
"""
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent / "app/src/main/res"
BG, PAPER, BACK, MIDDLE = "#111110", "#F4F4F0", "#5F5E5A", "#B4B2A9"
# The accents' fills as on a dark ground (Theme.kt flashOf, dark column)
SUNS = {
    "lime": "#D7F94A",
    "coral": "#FF7A59",
    "sky": "#7CC6FF",
    "amber": "#FFC53D",
    "mono": BG,
    "wallpaper": "@android:color/system_accent1_400",
}
MOUNTAINS = "M34,78 L48,61 L57,71 L64,65 L74,78 Z"
SUN = "M57,46 A7,7 0 1 0 71,46 A7,7 0 1 0 57,46 Z"
EVERYTHING = "M-100,-100 H208 V208 H-100 Z"
GAP = 2  # one colour can't overlap: a print is cut this far around the one in front of it
# Launchers show the middle 72dp of the 108dp grid; at 0.9 the prints fill about three quarters of the mask and still sit
# inside its 66dp safe zone. The in-app logo (LogoMark in Components.kt) uses the same scale.
SCALE = 0.9


def rounded(x, y, w, h, r, backwards=False):
    """A rounded rectangle path, clockwise; [backwards] runs it the other way, so inside another shape it's a hole."""
    f = lambda v: "%g" % v
    if not backwards:
        return (f"M{f(x + r)},{f(y)} H{f(x + w - r)} A{f(r)},{f(r)} 0 0 1 {f(x + w)},{f(y + r)} V{f(y + h - r)} "
                f"A{f(r)},{f(r)} 0 0 1 {f(x + w - r)},{f(y + h)} H{f(x + r)} A{f(r)},{f(r)} 0 0 1 {f(x)},{f(y + h - r)} "
                f"V{f(y + r)} A{f(r)},{f(r)} 0 0 1 {f(x + r)},{f(y)} Z")
    return (f"M{f(x + r)},{f(y)} A{f(r)},{f(r)} 0 0 0 {f(x)},{f(y + r)} V{f(y + h - r)} A{f(r)},{f(r)} 0 0 0 {f(x + r)},{f(y + h)} "
            f"H{f(x + w - r)} A{f(r)},{f(r)} 0 0 0 {f(x + w)},{f(y + h - r)} V{f(y + r)} A{f(r)},{f(r)} 0 0 0 {f(x + w - r)},{f(y)} Z")


# The prints on the 108dp adaptive-icon grid, turned about (54, 55): back -14 degrees, middle 8, front square
PRINT_BEHIND = rounded(29, 30, 50, 50, 10)
PRINT_FRONT = rounded(29, 32, 50, 50, 10)


def outset(x, y, w, h, r):
    return rounded(x - GAP, y - GAP, w + 2 * GAP, h + 2 * GAP, r + GAP, backwards=True)


def colour(sun):
    return f"""        <group android:pivotX="54" android:pivotY="55" android:rotation="-14">
            <path android:fillColor="{BACK}" android:pathData="{PRINT_BEHIND}" />
        </group>
        <group android:pivotX="54" android:pivotY="55" android:rotation="8">
            <path android:fillColor="{MIDDLE}" android:pathData="{PRINT_BEHIND}" />
        </group>
        <path android:fillColor="{PAPER}" android:pathData="{PRINT_FRONT}" />
        <path android:fillColor="{BG}" android:pathData="{MOUNTAINS}" />
        <path android:fillColor="{sun}" android:pathData="{SUN}" />
"""


# A clip-path clips what comes after it in its group; inside the big rectangle the outset print runs backwards, so it's
# a hole (non-zero winding): everything except that print and a GAP around it
ONE_COLOUR = f"""        <group>
            <clip-path android:pathData="{EVERYTHING} {outset(29, 32, 50, 50, 10)}" />
            <group android:pivotX="54" android:pivotY="55" android:rotation="8">
                <path android:fillColor="#FFFFFF" android:pathData="{PRINT_BEHIND}" />
                <clip-path android:pathData="{EVERYTHING} {outset(29, 30, 50, 50, 10)}" />
                <!-- -22 here is -14 on the page: the back print -->
                <group android:pivotX="54" android:pivotY="55" android:rotation="-22">
                    <path android:fillColor="#FFFFFF" android:pathData="{PRINT_BEHIND}" />
                </group>
            </group>
        </group>
        <path android:fillColor="#FFFFFF" android:fillType="evenOdd" android:pathData="{PRINT_FRONT} {MOUNTAINS} {SUN}" />
"""


def vector(note, body, size=108, viewport=108, group=f'<group android:pivotX="54" android:pivotY="55" android:scaleX="{SCALE}" android:scaleY="{SCALE}" android:translateY="-1">'):
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/app_icon.py: change it there. {note} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">
    {group}
{body}    </group>
</vector>
"""


def adaptive(foreground, background="@color/launcher_bg", monochrome="ic_launcher_monochrome"):
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/app_icon.py: change it there. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="{background}" />
    <foreground android:drawable="@drawable/{foreground}" />
    <monochrome android:drawable="@drawable/{monochrome}" />
</adaptive-icon>
"""


# ---------- Disguises ----------
# Drawn straight on the 108dp grid, inside the 66dp safe circle about (54, 54), so no launcher's mask cuts them. The
# one-colour layer can't overlap shapes it needs to tell apart, so details are holes (paths run backwards) and shapes
# that would touch keep GAP between them.

def n(v):
    return ("%.2f" % v).rstrip("0").rstrip(".")


def rect(x, y, w, h, backwards=False):
    if not backwards:
        return f"M{n(x)},{n(y)} H{n(x + w)} V{n(y + h)} H{n(x)} Z"
    return f"M{n(x)},{n(y)} V{n(y + h)} H{n(x + w)} V{n(y)} Z"


def circle(cx, cy, r, backwards=False):
    sweep = 0 if backwards else 1
    return f"M{n(cx - r)},{n(cy)} A{n(r)},{n(r)} 0 1 {sweep} {n(cx + r)},{n(cy)} A{n(r)},{n(r)} 0 1 {sweep} {n(cx - r)},{n(cy)} Z"


def polygon(points, turn=0, about=(54, 54), backwards=False):
    """A closed outline through [points], clockwise as given, [turn] degrees about [about]."""
    c, s = math.cos(math.radians(turn)), math.sin(math.radians(turn))
    ax, ay = about
    at = [(ax + (x - ax) * c - (y - ay) * s, ay + (x - ax) * s + (y - ay) * c) for x, y in points]
    if backwards:
        at.reverse()
    return "M" + " L".join(f"{n(x)},{n(y)}" for x, y in at) + " Z"


def cross(cx, cy, arm, thick, turn=0, backwards=False):
    """A plus sign as one outline (so as a hole it stays one hole), [turn] degrees about its centre: 45 is a times sign."""
    t = thick / 2
    points = [(-t, -arm), (t, -arm), (t, -t), (arm, -t), (arm, t), (t, t), (t, arm), (-t, arm), (-t, t), (-arm, t), (-arm, -t), (-t, -t)]
    return polygon([(cx + x, cy + y) for x, y in points], turn, (cx, cy), backwards)


def paths(*shapes):
    """(colour, pathData) pairs as vector paths."""
    return "".join(f'        <path android:fillColor="{colour}" android:pathData="{data}" />\n' for colour, data in shapes)


WHITE = "#FFFFFF"

# Calculator: four keys, plus, minus, times and an amber equals
KEY, KEY_GAP = 20, 4
KEYS = [(32, 32), (32 + KEY + KEY_GAP, 32), (32, 32 + KEY + KEY_GAP), (32 + KEY + KEY_GAP, 32 + KEY + KEY_GAP)]


def calculator_signs(backwards=False):
    (a, b), (c, d), (e, f), (g, h) = [(x + KEY / 2, y + KEY / 2) for x, y in KEYS]
    return [
        cross(a, b, 5, 2.6, backwards=backwards),
        rect(c - 5, d - 1.3, 10, 2.6, backwards),
        cross(e, f, 5, 2.6, 45, backwards),
        rect(g - 5, h - 3.6, 10, 2.6, backwards) + " " + rect(g - 5, h + 1, 10, 2.6, backwards),
    ]


def calculator(mono):
    slate, paper, amber = "#2F3A45", PAPER, "#FFB547"
    keys = [rounded(x, y, KEY, KEY, 5) for x, y in KEYS]
    if mono:
        return paths(*[(WHITE, key + " " + sign) for key, sign in zip(keys, calculator_signs(backwards=True))])
    return paths(*[(amber if i == 3 else paper, key) for i, key in enumerate(keys)], *[(slate, sign) for sign in calculator_signs()])


# Notes: a sheet with a heading and three lines of writing
NOTE_LINES = [(40, 36, 20, 4), (40, 46, 28, 3), (40, 54, 28, 3), (40, 62, 18, 3)]


def notes(mono):
    sheet = rounded(33, 28, 42, 52, 6)
    if mono:
        return paths((WHITE, sheet + " " + " ".join(rounded(*line, line[3] / 2, backwards=True) for line in NOTE_LINES)))
    return paths(("#FFFDF5", sheet), *[("#8A7A4F", rounded(*line, line[3] / 2)) for line in NOTE_LINES])


# Files: a folder, its front panel over the back with the tab
def files(mono):
    tab, back, front = rounded(30, 32, 20, 44 - GAP - 32, 3), rounded(30, 36, 48, 38, 5), rounded(30, 44, 48, 30, 5)
    if mono:
        # The gap between front and back is a hole across the folder, just above the front panel
        return paths((WHITE, tab), (WHITE, back + " " + rect(30, 44 - GAP, 48, GAP, backwards=True)))
    return paths(("#BFD3F0", tab), ("#BFD3F0", back), (PAPER, front))


# Clock: a face at three o'clock, the two hands one outline so in one colour they're one hole
def clock_hands(backwards=False):
    t = 2
    return polygon([(54 - t, 41), (54 + t, 41), (54 + t, 54 - t), (64, 54 - t), (64, 54 + t), (54 - t, 54 + t)], backwards=backwards)


CLOCK_TICKS = [(52.5, 34, 3, 4), (70, 52.5, 4, 3), (52.5, 70, 3, 4), (34, 52.5, 4, 3)]  # 12, 3, 6 and 9


def clock(mono):
    face = circle(54, 54, 22)
    if mono:
        return paths((WHITE, " ".join([face, clock_hands(backwards=True)] + [rect(*tick, backwards=True) for tick in CLOCK_TICKS])))
    return paths((PAPER, face), *[("#8A94A0", rect(*tick)) for tick in CLOCK_TICKS], ("#2F3A45", clock_hands()))


# Compass: a dial with the needle turned toward north-east; its north half red, as compasses have it
NEEDLE_NORTH = [(54, 38), (58, 54), (50, 54)]
NEEDLE_SOUTH = [(50, 54), (58, 54), (54, 70)]


def compass(mono):
    dial = circle(54, 54, 22)
    ticks = [(52.5, 34, 3, 4), (70, 52.5, 4, 3), (52.5, 70, 3, 4), (34, 52.5, 4, 3)]
    if mono:
        needle = polygon([(54, 38), (58, 54), (54, 70), (50, 54)], 40, backwards=True)
        return paths((WHITE, " ".join([dial, needle] + [rect(*tick, backwards=True) for tick in ticks])))
    return paths((PAPER, dial), *[("#8A94A0", rect(*tick)) for tick in ticks],
                 ("#E5484D", polygon(NEEDLE_NORTH, 40)), ("#2F3A45", polygon(NEEDLE_SOUTH, 40)))


# Scanner: a page inside the four corner marks of a scan, a scan line across it
def bracket(x, y, dx, dy):
    """A corner mark at (x, y), its arms running [dx] and [dy] (each 1 or -1)."""
    arm, t = 9, 3
    return polygon([(x, y), (x + dx * arm, y), (x + dx * arm, y + dy * t), (x + dx * t, y + dy * t), (x + dx * t, y + dy * arm), (x, y + dy * arm)])


BRACKETS = [bracket(35, 29, 1, 1), bracket(73, 29, -1, 1), bracket(35, 79, 1, -1), bracket(73, 79, -1, -1)]


def scanner(mono):
    page = rounded(41, 35, 26, 38, 3)
    if mono:
        # The scan line is a hole across the page and two stubs beside it, GAP clear of its edges
        line = rect(41, 52.5, 26, 3, backwards=True)
        return paths((WHITE, page + " " + line), *[(WHITE, b) for b in BRACKETS], (WHITE, rect(35, 52.5, 4, 3)), (WHITE, rect(69, 52.5, 4, 3)))
    return paths(*[(PAPER, b) for b in BRACKETS], (PAPER, page), ("#F5A524", rect(35, 52.5, 38, 3)))


# Authenticator: a shield with a keyhole
SHIELD = "M54,30 L74,37 V53 C74,65 65,73 54,78 C43,73 34,65 34,53 V37 Z"


def keyhole(backwards=False):
    if not backwards:
        return "M51,53 A6,6 0 1 1 57,53 L58.5,64 H49.5 Z"
    return "M51,53 L49.5,64 H58.5 L57,53 A6,6 0 1 0 51,53 Z"


def authenticator(mono):
    if mono:
        return paths((WHITE, SHIELD + " " + keyhole(backwards=True)))
    return paths((PAPER, SHIELD), ("#6A4FC0", keyhole()))


# Workspace: a briefcase, its belt broken by the clasp
def workspace(mono):
    handle = rounded(44, 30, 20, 14, 4) + " " + rounded(48, 34, 12, 10, 2, backwards=True)
    body = rounded(30, 38, 48, 36, 6)
    belt = [(30, 53, 20, 3), (58, 53, 20, 3)]  # either side of the clasp
    if mono:
        return paths((WHITE, handle), (WHITE, body + " " + " ".join(rect(*b, backwards=True) for b in belt)))
    return paths(("#C9CCD6", handle), (PAPER, body), *[("#34477A", rect(*b)) for b in belt], ("#FFC53D", rounded(50, 50, 8, 9, 2)))


# name: (background, drawing). Names match Disguise in Disguise.kt and the ".Disguise<Name>" aliases in the manifest.
DISGUISES = {
    "calculator": ("#2F3A45", calculator),
    "clock": ("#E8743B", clock),
    "compass": ("#2F7D73", compass),
    "notes": ("#F2C14E", notes),
    "files": ("#3D6FB6", files),
    "scanner": ("#D2504A", scanner),
    "authenticator": ("#6A4FC0", authenticator),
    "workspace": ("#34477A", workspace),
}


def main():
    for accent, sun in SUNS.items():
        name = f"ic_launcher_foreground_{accent}"
        (ROOT / f"drawable/{name}.xml").write_text(vector(f"The Prints mark with a {accent} sun, on the launcher's #111110.", colour(sun)))
        (ROOT / f"mipmap-anydpi/ic_launcher_{accent}.xml").write_text(adaptive(name))
    (ROOT / "drawable/ic_launcher_monochrome.xml").write_text(vector("Themed icons (Android 13+): the prints in one colour, which Android tints.", ONE_COLOUR))
    # The notification icon: the 64 units the prints cover, so they fill 24dp
    (ROOT / "drawable/ic_notification.xml").write_text(
        vector("The notification icon: the one-colour prints, cropped to fill 24dp.", ONE_COLOUR, size=24, viewport=64,
               group='<group android:translateX="-22" android:translateY="-23">'))
    for name, (background, draw) in DISGUISES.items():
        base = f"ic_disguise_{name}"
        (ROOT / f"drawable/{base}_background.xml").write_text(
            vector(f"The {name} disguise's ground.", paths((background, rect(0, 0, 108, 108))), group="<group>"))
        (ROOT / f"drawable/{base}_foreground.xml").write_text(vector(f"The {name} disguise.", draw(mono=False), group="<group>"))
        (ROOT / f"drawable/{base}_monochrome.xml").write_text(
            vector(f"The {name} disguise in one colour, for themed icons.", draw(mono=True), group="<group>"))
        (ROOT / f"mipmap-anydpi/{base}.xml").write_text(adaptive(f"{base}_foreground", f"@drawable/{base}_background", f"{base}_monochrome"))
    print(f"{len(SUNS)} launcher icons, monochrome, notification, {len(DISGUISES)} disguises")


if __name__ == "__main__":
    main()
